/**
 * 定时任务详细配置项说明文档：
 * - main: 主入口函数的触发间隔秒数，需与云厂商提供的触发器周期对齐（阿里云最小周期 60s）
 * - tasks: 定义子任务逻辑映射，键名（Key）必须在 tasks/index.js 中有对应的方法实现
 *
 * 子任务时间配置格式支持以下四种：
 *
 * 1. 数字类型: 如 10 表示每隔 10 秒运行一次
 * 2. 字符串类型:
 *    - 支持单位后缀：'30s' (30秒)、'5m' (5分钟)、'2h' (2小时)
 *    - 支持精准时刻：'12:30:00' (每天中午 12点30分准时触发)
 * 3. 对象类型 (增强配置):
 *    - { seconds: 30 } 或 { minutes: 10 } 分别代表秒/分钟级别的频率
 *    - { daily: '14:00:00' } 代表每日定时触发
 *    - { enabled: false } 可用于代码级别动态控制任务的开启或关闭
 *    - { desc: '任务说明' } 为任务逻辑提供可读性描述
 * 4. 数组类型 (组合配置):
 *    - ['10s', '08:00:00'] 同时应用间隔和定时两种触发规则
 *
 * 重要提示：子任务设置的间隔时间（总秒数）必须是 main 参数的整数倍，否则任务分发系统将因验证失败而不予执行。
 */
